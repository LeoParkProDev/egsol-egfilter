/** 같은 유형의 다른 규격 (내부 링크용) */
export function relatedSizes(current: FilterSize, limit = 6): FilterSize[] {
  const sameFootprint = filterSizes.filter(
    (s) => s.slug !== current.slug && s.w === current.w && s.h === current.h,
  );
  const sameType = filterSizes.filter(
    (s) =>
      s.slug !== current.slug &&
      s.type === current.type &&
      !(s.w === current.w && s.h === current.h),
  );
  return [...sameFootprint, ...sameType].slice(0, limit);
}
